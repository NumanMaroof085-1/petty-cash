def source_maps():
    source = (ROOT / 'pages/new-request/pettycash-api.js').read_text(encoding='utf-8')
    def choices(name):
        match = re.search(r'\b' + re.escape(name) + r':\s*\{(.*?)\n\s*\}', source, re.S)
        assert match, name
        return [(label, int(value)) for label, value in re.findall(r'"([^"]+)"\s*:\s*(\d+)', match[1])]
    units_match = re.search(r'\bunits:\s*\[(.*?)\n\s*\],', source, re.S)
    units = re.findall(r'\["([^"]+)",\s*"[^"]+"\]', units_match[1])
    assert len(units) == 23
    for key, records in [('requests', REQUEST), ('lineItems', LINES)]:
        block = re.search(r'\b' + key + r':\s*\{\s*id:\s*"hr_.*?\n\s*\}', source, re.S)
        assert block, key
        used = set(re.findall(r':\s*"(hr_\w+)"', block[0]))
        assert used.issubset({row[1] for row in records}), (key, used)
    assert len(REQUEST) == 18 and len(LINES) == 9
    assert len({row[1] for row in REQUEST + LINES}) == 27
    flow = (ROOT / 'flows/clarifications/CLARIFICATION_SETUP.md').read_text(encoding='utf-8')
    for field in ['hr_workflowstage','hr_currentapprovalid','hr_reviewround','hr_activeclarification']:
        assert field in flow
    module = (ROOT / 'shared/modules/pettycash-modules.js').read_text(encoding='utf-8')
    assert 'hr_managercomments' in module
    return choices, units

def paragraph(doc, text='', style=None, after=5):
    p = doc.add_paragraph(text, style)
    p.paragraph_format.space_after = Pt(after)
    return p

def bold_note(doc, label, text):
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(8)
    p.add_run(label + ' ').bold = True
    p.add_run(text)
    return p

def table(doc, headers, records, widths):
    t = doc.add_table(rows=1, cols=len(headers))
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    for col, width in zip(t.columns, widths):
        col.width = Inches(width)
    props = t._tbl.tblPr
    borders = OxmlElement('w:tblBorders')
    for name in ['top','left','bottom','right','insideH','insideV']:
        edge = OxmlElement('w:' + name)
        for key, value in [('val','single'),('sz','4'),('color','D9D9D9')]:
            edge.set(qn('w:' + key), value)
        borders.append(edge)
    props.append(borders)
    for values in [headers, *records]:
        row = t.rows[0] if values is headers else t.add_row()
        header = values is headers
        trpr = row._tr.get_or_add_trPr()
        trpr.append(OxmlElement('w:cantSplit'))
        if header:
            trpr.append(OxmlElement('w:tblHeader'))
        for index, (cell, text, width) in enumerate(zip(row.cells, values, widths)):
            cell.width = Inches(width)
            cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
            tcpr = cell._tc.get_or_add_tcPr()
            margins = OxmlElement('w:tcMar')
            for side, amount in [('top',60),('bottom',60),('left',100),('right',100)]:
                item = OxmlElement('w:' + side)
                item.set(qn('w:w'), str(amount)); item.set(qn('w:type'),'dxa')
                margins.append(item)
            tcpr.append(margins)
            shade = OxmlElement('w:shd')
            shade.set(qn('w:fill'),'243B53' if header else ('F2F5F8' if len(t.rows) % 2 == 0 else 'FFFFFF'))
            tcpr.append(shade)
            p = cell.paragraphs[0]
            p.paragraph_format.space_after = Pt(0)
            p.paragraph_format.line_spacing = 1.04
            if index == 2:
                p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            run = p.add_run(text)
            run.font.name = 'Calibri'
            run.font.size = Pt(9.5)
            run.font.color.rgb = RGBColor.from_string('FFFFFF' if header else '000000')
            run.bold = header or index == 0
            if not header and len(headers) == 4 and index == 1:
                run.font.name = 'Consolas'; run.font.size = Pt(9)
    return t

def heading(doc, title, logical, entity_set, primary):
    paragraph(doc, title, 'Heading 1', 5)
    paragraph(doc, f'Logical name: {logical}    |    Entity set: {entity_set}', after=2)
    paragraph(doc, f'Primary key: {primary}', after=8)

def main():
    choices, units = source_maps()
    doc = Document()
    section = doc.sections[0]
    section.orientation = WD_ORIENT.LANDSCAPE
    section.page_width, section.page_height = Inches(11.6929), Inches(8.2677)
    section.top_margin = section.bottom_margin = Inches(.5)
    section.left_margin = section.right_margin = Inches(.55)
    section.header_distance = section.footer_distance = Inches(.22)
    normal = doc.styles['Normal']
    normal.font.name = 'Calibri'; normal.font.size = Pt(10)
    normal.font.color.rgb = RGBColor(0,0,0)
    normal.paragraph_format.line_spacing = 1.08
    normal.paragraph_format.space_after = Pt(5)
    for name, size in [('Title',23),('Subtitle',11),('Heading 1',16),('Heading 2',12)]:
        style = doc.styles[name]
        style.font.name = 'Calibri'; style.font.size = Pt(size)
        style.font.color.rgb = RGBColor(0,0,0)
        style.font.underline = False
        style.paragraph_format.space_before = Pt(0)
        style.paragraph_format.space_after = Pt(5)
    doc.styles['Heading 2'].paragraph_format.space_before = Pt(6)
    # Some bundled Word defaults carry a blue paragraph border under Title.
    # Keep the title plain black and retain only the deliberate table borders.
    for border in list(doc.styles.element.xpath('.//w:pBdr')):
        border.getparent().remove(border)
    footer = section.footer.paragraphs[0]
    footer.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    run = footer.add_run('10 November 2026   |   Page ')
    run.font.size = Pt(9)
    field = OxmlElement('w:fldSimple'); field.set(qn('w:instr'),'PAGE')
    footer._p.append(field)

    paragraph(doc, 'Petty Cash Request and Line Item Tables', 'Title', 2)
    paragraph(doc, 'Used columns for Business Central source mapping', 'Subtitle', 6)
    heading(doc,'Petty Cash Request','hr_pettycashrequest','hr_pettycashrequests','hr_pettycashrequestid')
    table(doc,['Column','Logical name','Data type','Purpose'],REQUEST,[1.52,2.37,1.65,5.05])

    doc.add_page_break()
    paragraph(doc,'Petty Cash Request Choice Values','Heading 1',7)
    paragraph(doc,'Choice columns store integer codes. These are the mappings configured in the current project.',after=8)
    request_choices = [
        ('Payment Source\nhr_paymentsource',choices('paymentSource')),
        ('Payment Method\nhr_paymentmethod',choices('paymentMethod')),
        ('Approval Status\nhr_approvalstatus',choices('approvalStatus')),
        ('ERP Sync Status\nhr_erpsyncstatus',choices('erpSyncStatus')),
        ('Workflow Stage\nhr_workflowstage',WORKFLOW)
    ]
    table(doc,['Column','Stored codes and labels'],
          [(name,'\n'.join(str(code) + ' = ' + label for label,code in values)) for name,values in request_choices],
          [2.3,8.29])
    paragraph(doc,'Request Field Notes','Heading 2',6)
    bold_note(doc,'Transaction Date.', 'The app sends the selected date as an ISO date-time at 00:00:00 UTC. The retained schema does not establish the live Date Only or User Local behavior; confirm this before final Business Central date mapping.')
    bold_note(doc,'Receipt Image.', 'Despite its name, hr_receiptimage is used as a File column holding one PDF. The app accepts one PDF or combines selected JPG/PNG images into one PDF; its upload limit is 10 MB.')
    bold_note(doc,'Lookups.', 'Submitted By and Assigned Manager reference Contact; Department references hr_departments. Active Clarification references hr_requestclarification and does not contain the question or answer text itself.')
    bold_note(doc,'Amounts and workflow.', 'The application displays currency amounts in PKR. Approval Status is the final decision; Workflow Stage is process progress. A clarification leaves the request Pending. ERP Sync Status starts as Not Synced; the transfer to Business Central is not implemented by that field.')

    doc.add_page_break()
    heading(doc,'Petty Cash Line Item','hr_pettycashlineitem','hr_pettycashlineitems','hr_pettycashlineitemid')
    table(doc,['Column','Logical name','Data type','Purpose'],LINES,[1.52,2.37,1.65,5.05])
    paragraph(doc,'Category Values','Heading 2',6)
    table(doc,['Stored code','Label'],[(str(code),label) for label,code in choices('category')],[2.3,8.29])
    paragraph(doc,'Unit Values','Heading 2',6)
    paragraph(doc,'hr_unit stores one of these text values, not a numeric choice code: ' + '; '.join(units) + '.',after=8)
    bold_note(doc,'Relationship and totals.', 'One request can have many lines. hr_parentrequest stores the parent request GUID. Category and Other Category are line-item columns, not request-header columns. Total Price is stored as a Simple currency value supplied by the app.')

    doc.core_properties.title = 'Petty Cash Request and Line Item Tables'
    doc.core_properties.subject = 'Used Dataverse columns for Business Central mapping'
    doc.core_properties.author = 'Petty Cash Project'
    doc.core_properties.keywords = 'Dataverse, Business Central, petty cash, data dictionary'
    for border in list(doc._element.xpath('.//w:pBdr')):
        border.getparent().remove(border)
    OUT.parent.mkdir(parents=True,exist_ok=True)
    doc.save(OUT)
    # Verify contents and scope of the actual saved delivery file.
    saved = Document(OUT)
    texts = '\n'.join(p.text for p in saved.paragraphs) + '\n' + '\n'.join(c.text for t in saved.tables for r in t.rows for c in r.cells)
    for row in REQUEST + LINES:
        assert row[1] in texts
    assert len(saved.tables[0].rows) == 19
    assert len(saved.tables[2].rows) == 10
    assert 'hr_currentbalance' not in texts and 'hr_cashtransaction' not in texts
    print(f'Created {OUT.relative_to(ROOT)}: {len(REQUEST)} request columns, {len(LINES)} line-item columns; choice/unit values checked against source.')

if __name__ == '__main__':
    main()
